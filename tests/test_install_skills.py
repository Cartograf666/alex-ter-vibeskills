    def test_check_reports_edited_added_and_deleted_files_as_modified(self) -> None:
        with tempfile.TemporaryDirectory() as raw_temp:
            root = Path(raw_temp)
            command = self.clean_toolkit_command(root)
            subprocess.run(command, text=True, capture_output=True, check=True)
            skill = root / "installed" / "grill-requirements"
            changed = skill / "SKILL.md"
            original = changed.read_bytes()
            for mutation in ("edit", "delete", "add"):
                with self.subTest(mutation=mutation):
                    changed.write_bytes(original)
                    extra = skill / "extra.txt"
                    if extra.exists():
                        extra.unlink()
                    if mutation == "edit":
                        changed.write_bytes(original + b"\nEdited\n")
                    elif mutation == "delete":
                        changed.unlink()
                    else:
                        extra.write_text("extra\n", encoding="utf-8")
                    result = subprocess.run([*command, "--check"], text=True, capture_output=True)
                    self.assertEqual(result.returncode, 1, result.stderr)
                    self.assertIn("modified codex grill-requirements: 1 changed", result.stdout)


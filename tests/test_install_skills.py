    def test_git_failures_produce_null_provenance(self) -> None:
        for failure in (
            FileNotFoundError("git missing"),
            subprocess.CalledProcessError(128, ["git"], stderr="not a checkout"),
        ):
            with self.subTest(failure=failure):
                with mock.patch.object(install_skills.subprocess, "run", side_effect=failure):
                    state = install_skills.toolkit_state()
                self.assertIsNone(state["source_revision"])
                self.assertIsNone(state["source_dirty"])
        with mock.patch.object(install_skills.subprocess, "run", side_effect=[
            subprocess.CompletedProcess([], 0, stdout="a" * 40 + "\n"),
            subprocess.CalledProcessError(128, ["git"], stderr="status failed"),
        ]):
            state = install_skills.toolkit_state()
        self.assertIsNone(state["source_revision"])
        self.assertIsNone(state["source_dirty"])


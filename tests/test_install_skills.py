    def test_marker_rejects_invalid_shapes_and_types(self) -> None:
        with tempfile.TemporaryDirectory() as raw_temp:
            root = Path(raw_temp)
            staged = install_skills.stage_skill(ROOT / "skills" / "grill-requirements", root)
            marker = staged / install_skills.MANAGED_MARKER
            original = json.loads(marker.read_text())
            install_skills.assert_managed_install(staged, staged.name)
            nullable = {**original, "source_revision": None, "source_dirty": None}
            marker.write_text(json.dumps(nullable), encoding="utf-8")
            install_skills.assert_managed_install(staged, staged.name)
            invalid = [
                [], None, {"installer": "alex-ter-vibeskills", "skill": staged.name, "extra": True},
                *({**original, key: value} for key, value in (
                    ("installer", "foreign"), ("skill", "another-skill"),
                    ("marker_version", True), ("marker_version", 2.0),
                    ("toolkit_version", 2), ("installed_at", None),
                    ("source_revision", "not-a-revision"), ("source_dirty", 1),
                    ("files", []), ("files", {"SKILL.md": "not-a-hash"}),
                )),
                *({key: value for key, value in original.items() if key != missing}
                  for missing in original),
            ]
            for metadata in invalid:
                with self.subTest(metadata=metadata):
                    marker.write_text(json.dumps(metadata), encoding="utf-8")
                    with self.assertRaisesRegex(ValueError, "invalid ownership marker"):
                        install_skills.assert_managed_install(staged, staged.name)


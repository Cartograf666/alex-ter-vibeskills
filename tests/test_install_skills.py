from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import tempfile
import unittest
from datetime import datetime, timezone
from unittest import mock
from pathlib import Path

from scripts import install_skills


ROOT = Path(__file__).resolve().parents[1]
INSTALLER = ROOT / "scripts/install_skills.py"


class InstallSkillsTests(unittest.TestCase):
    def clean_toolkit_command(self, root: Path) -> list[str]:
        toolkit = root / "toolkit"
        (toolkit / "scripts").mkdir(parents=True)
        shutil.copy2(INSTALLER, toolkit / "scripts" / INSTALLER.name)
        shutil.copy2(ROOT / "VERSION", toolkit / "VERSION")
        shutil.copytree(ROOT / "skills", toolkit / "skills")
        for arguments in (
            ["init", "--quiet"],
            ["add", "scripts", "skills", "VERSION"],
            ["-c", "user.name=Installer Test", "-c", "user.email=installer@example.invalid",
             "-c", "core.hooksPath=/dev/null", "commit", "--quiet", "--no-gpg-sign", "-m", "Fixture"],
        ):
            subprocess.run(
                ["git", "-C", str(toolkit), *arguments],
                text=True, capture_output=True, check=True,
            )
        return [
            "python3", str(toolkit / "scripts" / INSTALLER.name),
            "--target", "codex", "--destination", str(root / "installed"),
        ]

    def test_fresh_install_records_version_timestamp_and_all_file_hashes(self) -> None:
        with tempfile.TemporaryDirectory() as raw_temp:
            root = Path(raw_temp)
            command = self.clean_toolkit_command(root)
            result = subprocess.run(command, text=True, capture_output=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            revision = subprocess.run(
                ["git", "-C", str(root / "toolkit"), "rev-parse", "HEAD"],
                text=True, capture_output=True, check=True,
            ).stdout.strip()
            for skill in (root / "installed").iterdir():
                raw_marker = (skill / install_skills.MANAGED_MARKER).read_text(encoding="utf-8")
                marker = json.loads(raw_marker)
                self.assertEqual(marker["marker_version"], 2)
                self.assertEqual(marker["installer"], "alex-ter-vibeskills")
                self.assertEqual(marker["skill"], skill.name)
                self.assertEqual(marker["toolkit_version"], (ROOT / "VERSION").read_text().strip())
                self.assertEqual(marker["source_revision"], revision)
                self.assertIs(marker["source_dirty"], False)
                installed_at = datetime.fromisoformat(marker["installed_at"].replace("Z", "+00:00"))
                self.assertEqual(installed_at.tzinfo, timezone.utc)
                self.assertEqual(installed_at.microsecond, 0)
                self.assertTrue(marker["installed_at"].endswith("Z"))
                expected = {
                    path.relative_to(skill).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
                    for path in sorted(skill.rglob("*"))
                    if path.is_file() and path.name != install_skills.MANAGED_MARKER
                }
                self.assertEqual(marker["files"], expected)
                self.assertEqual(list(marker["files"]), sorted(expected))
                self.assertEqual(raw_marker, json.dumps(marker, sort_keys=True) + "\n")

